package Basics;

public class SignCheck {
    public static void main(String[] args) {
        int number = -10;
        if (number > 0) {
            System.out.println("The Number id Positive");
        } else if (number < 0) {
            System.out.println("The Number is Negative");
        } else {
            System.out.println("The Number is Zero");
        }
    }
}
